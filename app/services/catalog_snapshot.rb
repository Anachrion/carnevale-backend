# Exports the authored catalog to versioned files, and imports it back. This is what makes the
# database-as-source-of-truth safe: the catalog a game creator builds in the production backoffice
# lives only on that one server's disk until it is snapshotted here, into git, where it is an
# off-box backup and a reviewable diff. Import rebuilds that catalog in another environment (a
# fresh prod, a teammate's machine).
#
# Since CARNEVALEB-82 this is the development seed (db/seeds.rb imports it), not the backup: the
# nightly pg_dump and storage copy are. It must still carry everything the backoffice can edit, or a
# contributor's local catalog silently lacks it.
#
# What is captured: the ability glossary and the spells; profiles (stats, keywords, abilities, and
# the advanced options: recruitable, flexible Leader and its partner, distinct discipline per copy,
# companion upgrade cost), their weapons and special rules (shared records, linked by a stable key),
# spell pools, granted spells and companions, their card references, and their illustration
# records — *including the uploaded image bytes*, so art added in production is not lost. What is not: render bookkeeping (internal_version, the digests), which is regenerated by
# rendering, and player data, which is not catalog.
#
# Import is additive and idempotent — find-or-update by natural key — so it is safe to run on a
# fresh database (disaster recovery, a new environment) and safe to re-run. It never deletes, so a
# record removed from the snapshot is left in place rather than cascaded through player data; prune
# those by hand if ever needed.
class CatalogSnapshot
  DEFAULT_DIR = Rails.root.join("db", "catalog").freeze
  BLOBS_SUBDIR = "blobs".freeze

  PROFILE_COLUMNS = %w[name faction version exclusive_weapons].concat(Catalog::Profile::STATS.map(&:to_s)).freeze
  WEAPON_COLUMNS = %w[name damage evasion penetration range abilities].freeze
  RULE_COLUMNS = %w[name description spell_name spell_cost spell_difficulty spell_description].freeze
  ABILITY_COLUMNS = %w[category name description].freeze
  SPELL_COLUMNS = %w[discipline name cost difficulty description cantrip].freeze
  # The advanced options (CARNEVALEB-84). flexible_leader_with and transforms_into are exported
  # apart, as the other profile's anchor identifier: ids are not portable.
  LINK_KEYS = %w[companions flexible_leader_with transforms_into].freeze
  PROFILE_FLAGS = %w[recruitable companion_upgrade_ducats flexible_leader distinct_discipline_per_copy].freeze
  POOL_COLUMNS = %w[of slot_count mage_slot_count unlimited grants_cantrip resets_each_round mentor_derived
                    distinct_from_other_pools].freeze
  GRANT_COLUMNS = %w[grant_kind consumes_slot resets_each_round unique_spell_name unique_spell_cost
                     unique_spell_difficulty unique_spell_description].freeze

  def self.export(dir: DEFAULT_DIR) = new(dir).export
  def self.import(dir: DEFAULT_DIR) = new(dir).import

  def initialize(dir)
    @dir = Pathname(dir)
    @blobs = @dir.join(BLOBS_SUBDIR)
  end

  # ── Export ────────────────────────────────────────────────────────────────────
  def export
    FileUtils.mkdir_p(@blobs)

    weapons = Catalog::Weapon.order(:name, :id).to_a
    rules   = Catalog::SpecialRule.order(:name, :id).to_a
    @weapon_key = stable_keys(weapons) { |w| w.name }
    @rule_key   = stable_keys(rules) { |r| r.name.presence || r.spell_name }

    write_yaml("abilities.yml", Catalog::Ability.order(:category, :name).map { |a| a.slice(*ABILITY_COLUMNS) })
    write_yaml("spells.yml", Catalog::Spell.order(:discipline, :name).map { |sp| sp.slice(*SPELL_COLUMNS) })
    write_yaml("weapons.yml", weapons.map { |w| { "key" => @weapon_key[w.id] }.merge(w.slice(*WEAPON_COLUMNS)) })
    write_yaml("special_rules.yml", rules.map { |r| { "key" => @rule_key[r.id] }.merge(r.slice(*RULE_COLUMNS)) })
    write_yaml("profiles.yml", exported_profiles)

    { weapons: weapons.size, special_rules: rules.size, profiles: Catalog::Profile.count, blobs: @blobs.children.count { |c| c.file? } }
  end

  # ── Import ────────────────────────────────────────────────────────────────────
  def import
    tally = Hash.new(0)

    ActiveRecord::Base.transaction do
      # The glossary first: profiles and weapons are validated against it.
      import_abilities(read_yaml("abilities.yml"), tally)
      import_spells(read_yaml("spells.yml"), tally)
      weapon_by_key = upsert_shared(read_yaml("weapons.yml"), Catalog::Weapon, WEAPON_COLUMNS, tally, :weapons)
      rule_by_key   = upsert_shared(read_yaml("special_rules.yml"), Catalog::SpecialRule, RULE_COLUMNS, tally, :special_rules)

      profiles = read_yaml("profiles.yml")
      profiles.each { |data| import_profile(data, weapon_by_key, rule_by_key, tally) }
      # Companions and flexible Leader partners name other profiles, which now all exist.
      clear_transformations(profiles)
      profiles.each { |data| import_profile_links(data) }
    end

    # An import can rewrite any profile's ducats/keywords, which feed gang validity — recompute the
    # cached selection_valid/selection_errors for every existing gang so they don't read stale (B-24).
    Gang::List.find_each(&:refresh_selection_validity)

    tally
  end

  private

  # ── Export helpers ──────────────────────────────────────────────────────────────
  def exported_profiles
    scope = Catalog::Profile
      .includes(:card_references, { profile_weapons: :weapon }, { profile_special_rules: :special_rule },
                { profile_spell_pools: :profile_spell_pool_disciplines }, { profile_granted_spells: :spell },
                { profile_companions: { companion_profile: :card_references } }, { flexible_leader_with: :card_references },
                { transforms_into: :card_references },
                illustrations: { image_attachment: :blob })
      .order(:faction, :name, :id)

    scope.map do |profile|
      profile.slice(*PROFILE_COLUMNS, *PROFILE_FLAGS).merge(
        "keywords" => profile.keywords,
        "abilities" => profile.abilities,
        "flexible_leader_with" => profile.flexible_leader_with && profile_anchor(profile.flexible_leader_with),
        "transforms_into" => profile.transforms_into && profile_anchor(profile.transforms_into),
        "weapons" => profile.profile_weapons.sort_by(&:position).map { |pw| @weapon_key[pw.weapon_id] },
        "special_rules" => profile.profile_special_rules.sort_by(&:position).map { |pr| @rule_key[pr.special_rule_id] },
        "spell_pools" => profile.profile_spell_pools.sort_by(&:position).map { |pool| exported_pool(pool) },
        "granted_spells" => profile.profile_granted_spells.sort_by(&:position).map { |grant| exported_grant(grant) },
        "companions" => profile.profile_companions.map { |pc| exported_companion(pc) }.sort_by { |row| row["profile"] },
        "card_references" => profile.card_references.sort_by(&:identifier).map { |cr| cr.slice("identifier", "name", "illustration_number") },
        "illustrations" => profile.illustrations.sort_by(&:number).map { |illus| exported_illustration(profile, illus) }
      )
    end
  end

  # Spell pools, granted spells and companions (CARNEVALEB-84), with their references made portable:
  # special rules by stable key, spells by discipline and name, profiles by anchor identifier.
  def exported_pool(pool)
    pool.slice(*POOL_COLUMNS).merge(
      "special_rule" => pool.special_rule_id && @rule_key[pool.special_rule_id],
      "disciplines" => pool.disciplines.sort
    )
  end

  def exported_grant(grant)
    grant.slice(*GRANT_COLUMNS).merge(
      "spell" => grant.spell && grant.spell.slice("discipline", "name"),
      "special_rule" => grant.special_rule_id && @rule_key[grant.special_rule_id]
    )
  end

  def exported_companion(profile_companion)
    { "profile" => profile_anchor(profile_companion.companion_profile) }
      .merge(profile_companion.slice("base_quantity", "upgraded_quantity"))
  end

  def exported_illustration(profile, illus)
    data = illus.slice("number", "path", "offset_x", "offset_y", "zoom", "flipped")
    data["image"] = export_blob(profile, illus) if illus.image.attached?
    data
  end

  # Writes the uploaded image bytes to blobs/ and returns the filename to record in the YAML. Named
  # after the profile's anchor identifier and the illustration number, so it is stable and unique.
  def export_blob(profile, illus)
    ext = illus.image.filename.extension.presence || "bin"
    filename = "#{profile_anchor(profile)}-illus#{illus.number}.#{ext}"
    @blobs.join(filename).binwrite(illus.image.download)
    filename
  end

  # A profile's stable identity across environments: its first card reference's identifier, which
  # is globally unique. (Every profile has at least one.)
  def profile_anchor(profile)
    profile.card_references.min_by(&:identifier)&.identifier || "profile-#{profile.name.parameterize}"
  end

  # A deterministic, collision-free key per shared record, so profiles can reference their weapons
  # and rules by something stable — names are not unique in the catalog, ids are not portable.
  def stable_keys(records)
    used = Hash.new(0)
    records.each_with_object({}) do |record, map|
      base = yield(record).to_s.parameterize.presence || "item"
      used[base] += 1
      map[record.id] = used[base] == 1 ? base : "#{base}-#{used[base]}"
    end
  end

  # ── Import helpers ──────────────────────────────────────────────────────────────
  # Upsert weapons or special rules, returning a key => record map for wiring up profiles. Matched
  # by their full attribute set, so identical rows collapse and same-named-but-different rows stay
  # distinct — the natural-key problem the export's `key` sidesteps for associations. json columns
  # (a weapon's abilities) are compared in Ruby: the `json` type has no `=` operator to query on.
  def upsert_shared(rows, klass, columns, tally, bucket)
    json_columns = columns.select { |c| klass.columns_hash[c].type == :json }
    scalar_columns = columns - json_columns

    rows.each_with_object({}) do |row, map|
      candidates = klass.where(row.slice(*scalar_columns))
      record = candidates.detect { |c| json_columns.all? { |col| c[col] == row[col] } } ||
               klass.create!(row.slice(*columns)).tap { tally[bucket] += 1 }
      map[row.fetch("key")] = record
    end
  end

  def import_profile(data, weapon_by_key, rule_by_key, tally)
    identifiers = data.fetch("card_references").map { |cr| cr.fetch("identifier") }
    existing = Catalog::CardReference.where(identifier: identifiers).first&.profile
    profile = existing || Catalog::Profile.new
    was_new = profile.new_record?

    # PROFILE_FLAGS are only in snapshots taken since CARNEVALEB-84; slice skips them in older ones.
    profile.assign_attributes(data.slice(*PROFILE_COLUMNS, *PROFILE_FLAGS).merge(
      "keywords" => data.fetch("keywords"), "abilities" => data.fetch("abilities")
    ))
    profile.save!
    tally[was_new ? :profiles_created : :profiles_updated] += 1

    import_card_references(profile, data.fetch("card_references"))
    import_illustrations(profile, data.fetch("illustrations"))
    profile.replace_weapons!(data.fetch("weapons").map { |k| weapon_by_key.fetch(k).id })
    profile.replace_special_rules!(data.fetch("special_rules").map { |k| rule_by_key.fetch(k).id })
    # Same for pools and grants: an older snapshot says nothing about them, so the current set stands.
    profile.replace_spell_pools!(data["spell_pools"]&.map { |row| imported_pool(row, rule_by_key) })
    profile.replace_granted_spells!(data["granted_spells"]&.map { |row| imported_grant(row, rule_by_key) })
  end

  def imported_pool(row, rule_by_key)
    row.slice(*POOL_COLUMNS).symbolize_keys.merge(
      special_rule_id: row["special_rule"] && rule_by_key.fetch(row["special_rule"]).id,
      disciplines: Array(row["disciplines"])
    )
  end

  def imported_grant(row, rule_by_key)
    spell = row["spell"] && Catalog::Spell.find_by!(discipline: row["spell"].fetch("discipline"), name: row["spell"].fetch("name"))
    row.slice(*GRANT_COLUMNS).symbolize_keys.merge(
      spell_id: spell&.id,
      special_rule_id: row["special_rule"] && rule_by_key.fetch(row["special_rule"]).id
    )
  end

  # A pair can move between profiles from one snapshot to the next (C -> B here, A -> B in the
  # snapshot). Assigned in file order, A would meet C still holding B and the uniqueness rule would
  # fail the whole import, so every pair the snapshot speaks for is cleared first and set again in
  # the links pass. Within the transaction, so a failed import still leaves them as they were.
  def clear_transformations(profiles)
    anchors = profiles.select { |data| data.key?("transforms_into") }
                      .map { |data| data.fetch("card_references").map { |cr| cr.fetch("identifier") }.min }
    ids = Catalog::CardReference.where(identifier: anchors).select(:profile_id)
    Catalog::Profile.where(id: ids).or(Catalog::Profile.where(transforms_into_id: ids))
                    .update_all(transforms_into_id: nil)
  end

  # The second pass: companions, the flexible Leader partner and the transformation form
  # (CARNEVALEB-85), which name other profiles by their anchor identifier.
  def import_profile_links(data)
    return unless LINK_KEYS.any? { |key| data.key?(key) }

    profile = profile_by_anchor(data.fetch("card_references").map { |cr| cr.fetch("identifier") }.min)
    partner = data["flexible_leader_with"] && profile_by_anchor(data["flexible_leader_with"])
    profile.update!(flexible_leader_with: partner) if data.key?("flexible_leader_with")
    if data.key?("transforms_into")
      profile.update!(transforms_into: data["transforms_into"] && profile_by_anchor(data["transforms_into"]))
    end
    return unless data.key?("companions")

    profile.replace_companions!(data["companions"].map do |row|
      { companion_profile_id: profile_by_anchor(row.fetch("profile")).id,
        base_quantity: row.fetch("base_quantity"), upgraded_quantity: row.fetch("upgraded_quantity") }
    end)
  end

  def profile_by_anchor(identifier)
    Catalog::CardReference.find_by!(identifier: identifier).profile
  end

  # The glossary and the spells (CARNEVALEB-86 made them editable): upserted by natural key.
  def import_abilities(rows, tally)
    rows.each do |row|
      ability = Catalog::Ability.find_or_initialize_by(category: row.fetch("category"), name: row.fetch("name"))
      tally[:abilities] += 1 if ability.new_record?
      ability.update!(description: row.fetch("description"))
    end
  end

  def import_spells(rows, tally)
    rows.each do |row|
      spell = Catalog::Spell.find_or_initialize_by(discipline: row.fetch("discipline"), name: row.fetch("name"))
      tally[:spells] += 1 if spell.new_record?
      # One cantrip per discipline: a cantrip renamed in the backoffice arrives under its new name
      # while the seeds created the original, so the original steps down first. It is kept, not
      # deleted, since gangs may still reference it.
      if row["cantrip"]
        Catalog::Spell.where(discipline: spell.discipline, cantrip: true).where.not(id: spell.id).update_all(cantrip: false)
      end
      spell.update!(row.slice("cost", "difficulty", "description", "cantrip"))
    end
  end

  def import_card_references(profile, rows)
    rows.each do |row|
      ref = Catalog::CardReference.find_or_initialize_by(identifier: row.fetch("identifier"))
      ref.assign_attributes(profile: profile, name: row.fetch("name"), illustration_number: row.fetch("illustration_number"))
      ref.save!
    end
  end

  def import_illustrations(profile, rows)
    rows.each do |row|
      illus = profile.illustrations.find_or_initialize_by(number: row.fetch("number"))
      illus.assign_attributes(row.slice("path", "offset_x", "offset_y", "zoom", "flipped"))
      illus.path ||= ""
      attach_blob(illus, row["image"]) if row["image"].present?
      illus.save!
    end
  end

  def attach_blob(illus, filename)
    file = @blobs.join(filename)
    return unless file.exist?

    illus.image.purge if illus.image.attached?
    illus.image.attach(io: file.open("rb"), filename: filename)
  end

  # ── IO ──────────────────────────────────────────────────────────────────────────
  # as_json first, so the file holds plain Hashes/Arrays with string keys — ActiveRecord#slice
  # returns HashWithIndifferentAccess, which Psych would tag with its class and safe_load reject.
  def write_yaml(name, data)
    @dir.join(name).write(data.as_json.to_yaml)
  end

  def read_yaml(name)
    path = @dir.join(name)
    path.exist? ? YAML.safe_load(path.read) : []
  end
end
